function getNodeText(node: React.ReactNode): string {
  if (node == null || typeof node === "boolean") return ""
  if (typeof node === "string" || typeof node === "number") return String(node)
  if (Array.isArray(node)) return node.map(getNodeText).join("")
  if (React.isValidElement<{ children?: React.ReactNode }>(node)) {
    return getNodeText(node.props.children)
  }
  return ""
}

function countSelectItems(children: React.ReactNode): number {
  let count = 0
  React.Children.forEach(children, (child) => {
    if (!React.isValidElement<{ children?: React.ReactNode }>(child)) return
    if (child.type === SelectItem) {
      count += 1
      return
    }
    if (child.props.children != null) {
      count += countSelectItems(child.props.children)
    }
  })
  return count
}

function filterSelectChildren(children: React.ReactNode, query: string): React.ReactNode {
  const normalized = query.trim().toLowerCase()
  if (!normalized) return children

  return React.Children.map(children, (child) => {
    if (!React.isValidElement<{ children?: React.ReactNode }>(child)) return child

    if (child.type === SelectItem) {
      const text = getNodeText(child.props.children).toLowerCase()
      return text.includes(normalized) ? child : null
    }

    if (child.props.children == null) return child

    const nextChildren = filterSelectChildren(child.props.children, query)
    if (child.type === SelectGroup && countSelectItems(nextChildren) === 0) {
      return null
    }

    return React.cloneElement(child, undefined, nextChildren)
  })
}

function SelectContent({
  className,
  children,
  position = "item-aligned",
  align = "center",
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Content>) {
  const [query, setQuery] = React.useState("")
  const inputRef = React.useRef<HTMLInputElement>(null)
  const filteredChildren = React.useMemo(
    () => filterSelectChildren(children, query),
    [children, query],
  )
  const hasItems = countSelectItems(filteredChildren) > 0

  React.useEffect(() => {
    const frame = window.requestAnimationFrame(() => {
      inputRef.current?.focus()
    })
    return () => window.cancelAnimationFrame(frame)
  }, [])

  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        data-slot="select-content"
        data-align-trigger={position === "item-aligned"}
        className={cn(
          "relative z-50 flex max-h-60 min-w-36 origin-(--radix-select-content-transform-origin) flex-col overflow-hidden rounded-lg bg-popover text-popover-foreground shadow-md ring-1 ring-foreground/10 duration-100 data-[align-trigger=true]:animate-none data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
          position === "popper" &&
            "data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1",
          className,
        )}
        position={position}
        align={align}
        {...props}
        onCloseAutoFocus={(event) => {
          props.onCloseAutoFocus?.(event)
          setQuery("")
        }}
      >
        <div className="sticky top-0 z-20 shrink-0 border-b border-border bg-popover p-1.5">
          <div className="relative">
            <SearchIcon className="pointer-events-none absolute top-1/2 left-2 size-3.5 -translate-y-1/2 text-muted-foreground" />
            <input
              ref={inputRef}
              type="text"
              value={query}
              placeholder="Search..."
              aria-label="Search options"
              className="h-8 w-full rounded-md border border-input bg-transparent py-1 pr-2 pl-7 text-sm outline-none placeholder:text-muted-foreground focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
              onChange={(event) => setQuery(event.target.value)}
              onKeyDown={(event) => event.stopPropagation()}
              onPointerDown={(event) => event.stopPropagation()}
            />
          </div>
        </div>
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          data-position={position}
          className={cn(
            "min-h-0 flex-1 overflow-y-auto p-1",
            position === "popper" && "w-full min-w-(--radix-select-trigger-width)",
          )}
        >
          {hasItems ? (
            filteredChildren
          ) : (
            <div className="px-1.5 py-2 text-sm text-muted-foreground">No results.</div>
          )}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  )
}

